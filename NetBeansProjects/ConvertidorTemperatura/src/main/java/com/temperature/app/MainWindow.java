    private void changeComboBox() {

        DefaultComboBoxModel<String> model = null;

        if (radioFahrenheit.isSelected()) {
            model = new DefaultComboBoxModel<>(new String[]{"°C", "°K"});
        } else if (radioCelsius.isSelected()) {
            model = new DefaultComboBoxModel<>(new String[]{"°F", "°K"});
        } else if (radioKelvin.isSelected()) {
            model = new DefaultComboBoxModel<>(new String[]{"°C", "°F"});
        }

        jComboBox1.setModel(model);
    }

