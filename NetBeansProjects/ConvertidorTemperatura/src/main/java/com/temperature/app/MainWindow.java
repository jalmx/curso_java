    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed

        String combo = jComboBox1.getSelectedItem().toString();
        Temperature t = new Temperature();

        System.out.println(combo);
        String unit = "";
        if (radioFahrenheit.isSelected()) {
            double f = Double.parseDouble(inputData.getText());
            double resultado = 0;

            if (combo.endsWith("C")) {
                resultado = t.convertFahrenheitToCelsius(f);
                unit = "C";
            } else if (combo.endsWith("K")) {
                //aqui va la formula para convertir de F -> K
                resultado = t.convertFahrenheitToKelvin(f);
                unit = "K";
            }
            labelResult.setText(String.format("%.2f °%s", resultado, unit));

        } else if (radioCelsius.isSelected()) {
            double c = Double.parseDouble(inputData.getText());
            double resultado = 0;

            if (combo.endsWith("F")) {
                resultado = t.convertCelsiusToFahrenheit(c);
                unit = "F";
            } else if (combo.endsWith("K")) {
                resultado = t.convertCelsiusToKelvin(c);
                unit = "K";
            }

            labelResult.setText(String.format("%.2f °%s", resultado, unit));

        } else if (radioKelvin.isSelected()) {
            double k = Double.parseDouble(inputData.getText());
            double resultado = 0;

            if (combo.endsWith("C")) {
                resultado = t.convertKelvinToCelsius(k);
                unit = "C";

            } else if (combo.endsWith("F")) {
                resultado = t.convertKelvintoFahrenheit(k);
                unit = "F";
            }

            labelResult.setText(String.format("%.2f °%s", resultado, unit));

        }
    }//GEN-LAST:event_btnCalculateActionPerformed

