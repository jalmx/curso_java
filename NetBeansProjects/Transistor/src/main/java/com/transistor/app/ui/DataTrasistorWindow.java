    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {
            JFileChooser chooser = new JFileChooser(".");

            int result = chooser.showOpenDialog(this);

            if (result == JFileChooser.APPROVE_OPTION) {
                ReadTransistorData rd = new ReadTransistorData(chooser.getSelectedFile().getAbsolutePath());

                txtPathData.setText(chooser.getSelectedFile().getAbsolutePath());

                StringBuilder st = new StringBuilder();
                List<List<String>> rows = rd.getData();

                st.append(rows.get(0)).append("\n");
                st.append("--------------------------\n");

                for (int i = 1; i < rows.size(); i++) {
                    st.append(rows.get(i)).append("\n");
                }

                areaData.setText(st.toString());
                ReadTransistorData.saveData(rows);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar los datos");
            e.printStackTrace();
        }


    }//GEN-LAST:event_jButton1ActionPerformed

