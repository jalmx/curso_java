    private void loadData() {

        File fileLocal = new File(CONST.FILE_LOCAL);

        if (fileLocal.exists()) {
            ReadTransistorData rd = new ReadTransistorData(fileLocal.getAbsolutePath());
            txtPathData.setText(fileLocal.getAbsolutePath());

            StringBuilder st = new StringBuilder();
            List<List<String>> rows = rd.getData();

            st.append(rows.get(0)).append("\n");
            st.append("--------------------------\n");

            for (int i = 1; i < rows.size(); i++) {
                st.append(rows.get(i)).append("\n");
            }

            areaData.setText(st.toString());
        }else{
            
            String st = 
                    "EJEMPLO DE ARCHIVO CSV PARA ALMACENAR DATOS \n" +
                    "| name    | hfe  | VCE_sat |VBE_sat|\n" +
                    "| 2N2222A | 35   | 0.5     |0.6    |\n" +
                    "| 2N3904  | 100  | 0.2     |0.65   |\n";
            areaData.setText(st);
        }

    }

